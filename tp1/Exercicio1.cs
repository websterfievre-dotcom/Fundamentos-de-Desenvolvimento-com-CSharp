        /*
         * EXERCÍCIO 1 - Entender a Relação entre C# e .NET
         *
         * 1. O que é .NET?
         * 
         * .NET é uma plataforma de desenvolvimento criada pela Microsoft.
         * Ela fornece ferramentas, bibliotecas e um ambiente de execução
         * para criar diferentes tipos de aplicações, como programas desktop,
         * aplicações web e APIs.
         *
         * 2. Como o C# se integra ao .NET?
         * 
         * C# é uma linguagem de programação utilizada dentro da plataforma
         * .NET. Nós escrevemos o código em C#, e o .NET fornece os recursos
         * necessários para compilar e executar esse código.
         *
         * 3. Qual é o papel do CLR e do FCL?
         * 
         * O CLR (Common Language Runtime) é responsável pela execução dos
         * programas .NET. Ele também gerencia recursos como memória,
         * tratamento de exceções e segurança durante a execução.
         *
         * O FCL (Framework Class Library) é um conjunto de classes e
         * funcionalidades prontas que podemos utilizar nos programas,
         * como trabalhar com arquivos, textos, coleções e outros recursos.
         */
    }
