        /*
         * EXERCÍCIO 3 - Diferenças entre IDEs para Desenvolvimento em C#
         *
         * 1. Visual Studio
         *
         * É uma IDE completa da Microsoft e possui excelente suporte para
         * C# e .NET. Oferece ferramentas como depuração, testes, Git,
         * gerenciamento de projetos e integração com banco de dados.
         *
         * Vantagens:
         * - Excelente integração com C# e .NET.
         * - Possui muitas ferramentas de desenvolvimento integradas.
         * - Interface visual que facilita o trabalho com projetos.
         *
         * Desvantagens:
         * - É mais pesado e utiliza mais recursos do computador.
         * - Pode parecer complexo para quem está começando.
         *
         *
         * 2. Visual Studio Code
         *
         * É um editor de código leve e suporta várias linguagens através
         * de extensões. Pode ser utilizado para desenvolver em C#,
         * JavaScript, Python, Java e muitas outras linguagens.
         *
         * Vantagens:
         * - Leve e rápido.
         * - Suporta várias linguagens.
         * - Possui muitas extensões.
         * - Interface relativamente simples para iniciantes.
         *
         * Desvantagens:
         * - Algumas funcionalidades precisam ser instaladas através
         *   de extensões.
         * - Para projetos C# mais complexos pode exigir mais configuração.
         *
         *
         * 3. Rider
         *
         * Rider é uma IDE desenvolvida pela JetBrains e possui forte
         * suporte para C# e .NET. Também oferece ferramentas para
         * depuração, testes, Git e refatoração de código.
         *
         * Vantagens:
         * - Excelente suporte para C# e .NET.
         * - Boas ferramentas de análise e refatoração de código.
         * - Suporta diferentes tecnologias e linguagens.
         *
         * Desvantagens:
         * - Geralmente requer uma licença paga.
         * - Pode exigir um pouco de aprendizado para novos usuários.
         *
         *
         * RESUMO:
         *
         * Visual Studio = mais completo para desenvolvimento C#/.NET.
         * Visual Studio Code = mais leve, flexível e suporta muitas linguagens.
         * Rider = forte em C#/.NET e possui excelentes ferramentas de código.
         */
    }
}